import jwt from 'jsonwebtoken';
import User from '../models/User.js';

export const protect = async (req, res, next) => {
  let token;

  if (
    req.headers.authorization &&
    req.headers.authorization.startsWith('Bearer')
  ) {
    try {
      token = req.headers.authorization.split(' ')[1];
      let decoded;
      
      // Try verifying with current JWT_SECRET, fallback to legacy dev secret
      try {
        decoded = jwt.verify(token, process.env.JWT_SECRET || 'finwise_secret_jwt_key_2026');
      } catch (err) {
        decoded = jwt.verify(token, 'finwise_dev_secret_key_987654321');
      }

      req.user = await User.findById(decoded.id).select('-password');
      if (!req.user) {
        return res.status(401).json({
          success: false,
          message: 'User session has expired or user no longer exists. Please log in again.',
        });
      }

      next();
    } catch (error) {
      console.error('Auth verification error:', error.message);
      return res.status(401).json({
        success: false,
        message: 'Not authorized, token failed or expired',
      });
    }
  }

  if (!token) {
    return res.status(401).json({
      success: false,
      message: 'Not authorized, no bearer token provided',
    });
  }
};
